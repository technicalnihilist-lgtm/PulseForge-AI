package com.pulseforge.report

import com.pulseforge.model.ScanReport
import com.pulseforge.performance.OptimizationRecipe
import com.pulseforge.performance.PlannedAction

/**
 * Writes the optimization plan as Markdown, so it can leave the app and be pasted into a ticket,
 * a PR description or a build file.
 *
 * It contains only what the report already established: the prioritised actions, the build recipe
 * and the estimates, each labelled as an estimate where it is one.
 */
object OptimizationPlanWriter {

    fun write(report: ScanReport, plan: List<PlannedAction>, recipe: OptimizationRecipe): String = buildString {
        val manifest = report.apk.manifest
        appendLine("# Optimization plan - ${manifest?.packageName ?: report.apk.fileName}")
        appendLine()
        appendLine("Generated by PulseForge AI from report `${report.reportId}`.")
        appendLine("Analysis mode: ${report.meta.analysisMode}.")
        appendLine()
        appendLine("> This plan is derived from static analysis. Estimates are labelled; measurements are not.")
        appendLine()

        appendLine("## Summary")
        appendLine()
        appendLine("| Item | Value |")
        appendLine("|---|---|")
        appendLine("| APK size | ${formatBytes(report.apk.fileSizeBytes)} |")
        appendLine("| Planned actions | ${plan.size} |")
        appendLine("| Estimated saving | ${if (recipe.estimatedSavingBytes > 0) formatBytes(recipe.estimatedSavingBytes) else "not estimated"} |")
        appendLine("| Security score | ${report.scoring.security ?: "n/a"}/100 |")
        appendLine("| Performance score | ${report.scoring.performance ?: "n/a"}/100 |")
        appendLine()

        if (plan.isNotEmpty()) {
            appendLine("## Actions, in order")
            appendLine()
            plan.forEach { action ->
                appendLine("### ${action.priority}. ${action.title}")
                appendLine()
                appendLine("- Origin: ${action.origin}")
                appendLine("- Impact: ${action.impact.name.lowercase()}, effort: ${action.effort.name.lowercase()}")
                if (action.requiresSourceAccess) {
                    appendLine("- Requires source access: yes")
                } else {
                    appendLine("- Requires source access: no (report-only for a third-party app)")
                }
                appendLine()
                appendLine(action.rationale)
                if (action.steps.isNotEmpty()) {
                    appendLine()
                    action.steps.forEachIndexed { index, step -> appendLine("${index + 1}. $step") }
                }
                appendLine()
            }
        }

        if (!recipe.isEmpty) {
            appendLine("## Build recipe")
            appendLine()
            recipe.sections.forEach { section ->
                appendLine("### ${section.title}")
                appendLine()
                appendLine(section.rationale)
                if (section.estimatedSavingBytes != null && section.estimatedSavingBytes > 0) {
                    appendLine()
                    appendLine("Estimated saving: ${formatBytes(section.estimatedSavingBytes)} (estimate).")
                }
                appendLine()
                appendLine("Target: `${section.target}`")
                appendLine()
                appendLine("```${section.language}")
                appendLine(section.snippet)
                appendLine("```")
                appendLine()
            }
        }

        appendLine("## Notes")
        appendLine()
        recipe.notes.forEach { appendLine("- $it") }
        appendLine()
        appendLine("## What this plan cannot do")
        appendLine()
        report.meta.limitations.forEach { appendLine("- $it") }
        appendLine()
        appendLine("- PulseForge does not rebuild or re-sign an APK. Applying this plan requires your own build.")
        appendLine("- An installed third-party app cannot be modified at all: use the system App-info screen to revoke permissions or uninstall.")
    }

    private fun formatBytes(bytes: Long): String = when {
        bytes < 1024 -> "$bytes B"
        bytes < 1024 * 1024 -> "%.1f KB".format(bytes / 1024.0)
        else -> "%.1f MB".format(bytes / (1024.0 * 1024))
    }
}
